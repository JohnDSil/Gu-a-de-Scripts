# Esto es un comentario. Python lo ignora cuando ejecuta el código.
# Los comentarios sirven para explicar qué hace el código.
# Empieza siempre con el símbolo #

# La función print() muestra texto en la pantalla
print("¡Hola, mundo!")

# Puedes imprimir varias cosas en la misma línea separando con comas
print("Hola", "estudiante", "de", "informática")

# O usar varios print() uno detrás de otro (cada uno en una línea nueva)
print("Primera línea")
print("Segunda línea")
print("Tercera línea")

# También puedes imprimir una línea vacía para separar el contenido
print()
print("Esta línea tiene una línea vacía arriba")

# Para imprimir comillas dentro del texto, usa el otro tipo de comillas
print('Esto usa comillas simples y funciona igual')
print("Puedo incluir 'comillas simples' dentro de comillas dobles")

